package com.xworkz.polymorphism.book;

public class Book {
    public void title() {
        System.out.println("Generic Book Title");
    }

    public void author() {
        System.out.println("Unknown Author");
    }

    public void genre() {
        System.out.println("General");
    }

    public void price() {
        System.out.println("Price: 200 INR");
    }

    public void pages() {
        System.out.println("Pages: 300");
    }
}
