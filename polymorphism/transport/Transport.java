package com.xworkz.polymorphism.transport;

public class Transport {
    public void type() {
        System.out.println("Type: Generic Transport");
    }

    public void fuelType() {
        System.out.println("Fuel Type: Varies based on transport type.");
    }

    public void capacity() {
        System.out.println("Capacity: Varies based on transport.");
    }

    public void speed() {
        System.out.println("Speed: Varies based on transport type.");
    }

    public void usage() {
        System.out.println("Usage: Used for movement of people or goods.");
    }
}
