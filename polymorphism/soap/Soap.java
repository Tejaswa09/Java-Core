package com.xworkz.polymorphism.soap;

public class Soap {
    public void type() {
        System.out.println("Type: Generic Soap");
    }

    public void fragrance() {
        System.out.println("Fragrance: Varies based on soap type");
    }

    public void usage() {
        System.out.println("Usage: Used for cleaning and bathing.");
    }

    public void ingredients() {
        System.out.println("Ingredients: Varies (soap base, fragrance, colorants)");
    }

    public void packaging() {
        System.out.println("Packaging: Usually wrapped in plastic or paper.");
    }
}
