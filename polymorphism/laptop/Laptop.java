package com.xworkz.polymorphism.laptop;

public class Laptop {
    public void brand() {
        System.out.println("Brand: Generic Laptop");
    }

    public void model() {
        System.out.println("Model: Basic model");
    }

    public void processor() {
        System.out.println("Processor: Intel i5");
    }

    public void ram() {
        System.out.println("RAM: 8GB");
    }

    public void storage() {
        System.out.println("Storage: 512GB SSD");
    }

    public void price() {
        System.out.println("Price: Varies based on specifications");
    }
}
